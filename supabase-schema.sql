-- SUPABASE SQL SCHEMA: MEDIA PEMBELAJARAN BANGUN DATAR KELAS 4 SD
-- Cara Pakai:
-- 1. Buka Dashboard Supabase -> menu "SQL Editor" -> klik "New Query"
-- 2. Copy-paste seluruh isi file ini lalu klik tombol "Run"
-- ============================================================================

-- 1. Tabel untuk menyimpan Konten Halaman (Petunjuk, Tujuan Pembelajaran, Bahan Bacaan, Penyusun)
CREATE TABLE IF NOT EXISTS public.site_contents (
  key TEXT PRIMARY KEY,
  content JSONB NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Tabel untuk menyimpan Link Soal / Pustaka & QR Code (Ayo Berlatih & Daftar Pustaka)
CREATE TABLE IF NOT EXISTS public.external_links (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category TEXT NOT NULL DEFAULT 'pilihan-ganda', -- 'pilihan-ganda' | 'isian' | 'daftar-pustaka'
  title TEXT NOT NULL,
  description TEXT DEFAULT '',
  url TEXT NOT NULL,
  thumbnail_url TEXT DEFAULT '',
  custom_qr_url TEXT DEFAULT '', -- Jika kosong, aplikasi otomatis membuat QR Code dari URL!
  show_qr BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabel untuk menyimpan Video Pembelajaran (Link YouTube)
CREATE TABLE IF NOT EXISTS public.videos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  subtitle TEXT DEFAULT '',
  youtube_url TEXT NOT NULL,
  embed_url TEXT NOT NULL,
  thumbnail_url TEXT DEFAULT '/assets/images/thumb-video-1.png',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Tabel untuk menyimpan Soal Pilihan Ganda Interaktif (Game Membuka Kotak)
CREATE TABLE IF NOT EXISTS public.mc_questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  no INT NOT NULL,
  color TEXT DEFAULT '#ffb703',
  question TEXT NOT NULL,
  options JSONB NOT NULL,
  answer INT NOT NULL DEFAULT 0,
  explain TEXT DEFAULT '',
  image_url TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Tabel untuk menyimpan Soal Isian Interaktif
CREATE TABLE IF NOT EXISTS public.essay_questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  no INT NOT NULL,
  question TEXT NOT NULL,
  placeholder TEXT DEFAULT 'Ketik jawabanmu...',
  unit TEXT DEFAULT 'cm',
  expected_answers JSONB NOT NULL,
  solution_html TEXT DEFAULT '',
  image_url TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================================
-- AKTIFKAN ROW LEVEL SECURITY (RLS) & POLICY AGAR BISA DIBACA DAN DIUBAH GURU
-- ============================================================================
ALTER TABLE public.site_contents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.external_links ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.videos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mc_questions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.essay_questions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public all site_contents" ON public.site_contents;
CREATE POLICY "Public all site_contents" ON public.site_contents FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public all external_links" ON public.external_links;
CREATE POLICY "Public all external_links" ON public.external_links FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public all videos" ON public.videos;
CREATE POLICY "Public all videos" ON public.videos FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public all mc_questions" ON public.mc_questions;
CREATE POLICY "Public all mc_questions" ON public.mc_questions FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public all essay_questions" ON public.essay_questions;
CREATE POLICY "Public all essay_questions" ON public.essay_questions FOR ALL USING (true) WITH CHECK (true);

